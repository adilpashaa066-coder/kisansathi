export function getDistrictsForState(state: string): string[] {
  const districts = INDIA_LOCATIONS[state];
  if (!districts) return [];
  return Object.keys(districts);
}

export function getTaluksForDistrict(state: string, district: string): string[] {
  const taluks = INDIA_LOCATIONS[state]?.[district];
  if (!taluks) return [];
  return taluks;
}

export function isValidIndianLocation(state: string, district: string, taluk: string): boolean {
  const s = state.trim();
  const d = district.trim();
  const t = taluk.trim();
  if (!s || !d || !t) return false;
  const districts = INDIA_LOCATIONS[s];
  if (!districts) return false;
  const taluks = districts[d];
  if (!taluks) return false;
  return taluks.includes(t);
}
